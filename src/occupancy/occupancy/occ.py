    def create_map(self):
        if not hasattr(self, "ranges") or not hasattr(self, "angles"):
            return

        alpha = 0.1  # obstacle thickness, meters
        beta = 0.02  # angular width, radians
        z_max = self.range_max

        origin_x = -10.0
        origin_y = -10.0

        for gy in range(self.grid_height):
            for gx in range(self.grid_width):

                # grid cell -> world coordinates
                cell_x = origin_x + (gx + 0.5) * self.resolution
                cell_y = origin_y + (gy + 0.5) * self.resolution

                # distance and bearing from robot to cell
                r = np.sqrt((cell_x - self.x) ** 2 + (cell_y - self.y) ** 2)
                phi = np.arctan2(cell_y - self.y, cell_x - self.x) - self.angle
                phi = self.normalize_angle(phi)

                # find nearest laser beam
                diffs = np.abs([self.normalize_angle(phi - a) for a in self.angles])
                k = np.argmin(diffs)

                z_k = self.ranges[k]
                theta_k = self.angles[k]

                # inverse sensor model
                if r > min(z_max, z_k + alpha / 2.0) or abs(phi - theta_k) > beta / 2.0:
                    continue

                if z_k < z_max and abs(r - z_k) < alpha / 2.0:
                    self.log_odds[gy, gx] += self.l_occ - self.l0

                elif r <= z_k:
                    self.log_odds[gy, gx] += self.l_free - self.l0

        # convert log-odds to probability
        probs = 1.0 - 1.0 / (1.0 + np.exp(self.log_odds))

        occ_grid = np.full((self.grid_height, self.grid_width), -1, dtype=np.int8)

        occ_grid[probs >= self.threshold_p_free] = 0
        occ_grid[probs <= self.threshold_p_occ] = 100

        msg = OccupancyGrid()
        msg.header.stamp = self.get_clock().now().to_msg()
        msg.header.frame_id = "map"

        msg.info.map_load_time = self.get_clock().now().to_msg()
        msg.info.resolution = self.resolution
        msg.info.width = self.grid_width
        msg.info.height = self.grid_height

        msg.info.origin.position.x = origin_x
        msg.info.origin.position.y = origin_y
        msg.info.origin.position.z = 0.0
        msg.info.origin.orientation.w = 1.0

        msg.data = occ_grid.flatten().tolist()

        self.map_publisher.publish(msg)

