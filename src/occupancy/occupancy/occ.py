    def timer_callback(self):
        msg = Twist()
        R = np.array([
            [np.cos(self.angle), np.sin(self.angle)],
            [-np.sin(self.angle), np.cos(self.angle)]
        ])
        v = R @ (np.array([self.x, self.y]) - self.goals[self.current_goal])
        v = -self.k_a * v/np.linalg.norm(v)

        for i in self.cart_data:
            denom = np.linalg.norm(i)
            if denom != 0 and denom < self.ro:
                v_rep = self.k_r * (1/denom - 1/self.ro) * (1/denom ** 2)* i/denom
                v += v_rep

        angle_to_goal = np.arctan2(v[1], v[0])

        msg.angular.z = self.normalize_angle(angle_to_goal)
        msg.linear.x = v[0]
        if np.linalg.norm(np.array([self.x, self.y]) - self.goals[self.current_goal]) < 0.8:
            msg.linear.x = 0.0
            if self.normalize_angle(self.angle) < 0.15:
                self.get_logger().info(f"Rotating")
                msg.angular.z = -1.0
                #self.goal_orientations[self.current_goal] - self.angle
            else:
                msg.angular.z = 0.0
                self.get_logger().info(f"DONE!")
                if len(self.goals)-1 > self.current_goal:
                    self.current_goal+=1
        self.publisher.publish(msg)

    def odom_data_reader(self, msg):
        self.x = msg.pose.pose.position.x
        self.y = msg.pose.pose.position.y
        q = msg.pose.pose.orientation
        _, _, self.angle = euler_from_quaternion([q.x, q.y, q.z, q.w])

    def listener_callback(self, msg):
        ranges = np.array(msg.ranges)
        idx = np.array([ranges <= msg.range_max]) * np.array([ranges >= msg.range_min])
        self.range_max = msg.range_max
        #self.ro = msg.range_max
        idx = idx.reshape(-1)
        angles = msg.angle_min + np.arange(len(ranges))*msg.angle_increment
        self.angles = angles[idx]
        self.ranges = ranges[idx]
        polar_data = np.vstack([self.ranges, self.angles]).T
        cart_data = self.np_polar2cart(polar_data)
        self.cart_data = cart_data

    # function from HW 2
    def np_polar2cart(self, np_polar):
        x = np_polar[:, 0] * np.cos(np_polar[:,1]) + 0.45 #!!! change of frame
        y = np_polar[:, 0] * np.sin(np_polar[:,1])
        np_cart = np.vstack([x, y]).T
        return np_cart

    def normalize_angle(self, angle):
        while angle > np.pi:
            angle -= 2.0 * np.pi
        while angle < -np.pi:
            angle += 2.0 * np.pi
        return angle

